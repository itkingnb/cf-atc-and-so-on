ll qpow(ll a, ll k, ll p)
{
    ll res = 1;
    while (k)
    {
        if (k & 1)
            res = (ll)res * a % p;
        a = (ll)a * a % p;
        k >>= 1;
    }
    return res;
}
void solve(){
    int n,k;
    cin>>n>>k;
    vector<int>a(n);
    for(int i=0;i<n;i++){
        cin>>a[i];
    }
    int l=0,r=1e9+10;
    int ans=0;
    vector<int>b(n);
    auto check=[&](int x)->bool{
        for(int i=0;i<n;i++){
            b[i]=(a[i]>=x?1:-1);
        }
        vector<int>dp(n,-1e9);
        dp[0]=b[0];
        for(int i=1;i<min(n,k);i++){
            dp[i]=dp[i-1]+b[i];
        }
        for(int i=k;i<n;i++){
            if(i%k==0){
                dp[i]=max(dp[i-k],b[i]);
            }else{
                dp[i]=max(dp[i-1]+b[i],dp[i-k]);
            }
        }
        return dp.back()>0;
    };
    check(6);
    while(l<=r){
        int mid=(l+r)>>1;
        if(check(mid)){
            ans=mid;
            l=mid+1;
        }else{
            r=mid-1;
        }
    }
    cout<<ans;
}

int main(){
    ios_base::sync_with_stdio(0);
    cin.tie(0); cout.tie(0);
    int t=1;
    cin>>t;
    for(int i=0;i<t;i++){
        solve();
        cout<<'\n';
    }
    return 0;
}